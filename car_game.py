# The dial is split into four equal quarters, one per speed zone, so the needle
# crosses into a new colour exactly when the road changes to a new zone.
DIAL = [(0, 0.0), (30, 0.25), (50, 0.5), (100, 0.75), (MAX_KMH, 1.0)]


def dial_frac(v):
    v = clamp(v, 0, MAX_KMH)
    for i in range(1, len(DIAL)):
        if v <= DIAL[i][0]:
            (v0, f0), (v1, f1) = DIAL[i - 1], DIAL[i]
            return f0 + (f1 - f0) * (v - v0) / (v1 - v0)
    return 1.0


def dial_angle(v):
    return math.radians(225 - 270 * dial_frac(v))


def arc_band(cx, cy, r0, r1, v0, v1, color):
    steps = 12
    outer, inner = [], []
    for i in range(steps + 1):
        a = dial_angle(v0 + (v1 - v0) * i / steps)
        outer.append((cx + r1 * math.cos(a), cy - r1 * math.sin(a)))
        inner.append((cx + r0 * math.cos(a), cy - r0 * math.sin(a)))
    pygame.draw.polygon(screen, color, outer + inner[::-1])


