def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def lerp_color(a, b, t):
    t = clamp(t, 0.0, 1.0)
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def darken(c, f):
    return lerp_color(c, (0, 0, 0), f)


def lighten(c, f):
    return lerp_color(c, (255, 255, 255), f)


