"""Damsel in the Car: a crash-safety game for the Raspberry Pi 5.

Part of a Critical Making project on gender bias in vehicle crash safety.
The player dodges traffic with a rotary encoder; the faster they drive, the
worse the crash. After a crash the game shows the injury risk for men and
women at that speed, guides the player through a physical crash ramp, plays
a crash test replay and lights up two crash test dummies (addressable LEDs)
in the colour of the injury severity.

Hardware:
    Rotary encoder (KY-040): + pin 1, GND pin 9, CLK pin 11 (GPIO17),
                             DT pin 13 (GPIO27), SW pin 15 (GPIO22)
    LED chain (30 x WS2812): 5V pin 2, GND pin 6, DIN pin 19 (GPIO10) via 330 ohm
        LEDs 1-12  right side of the ramp, top to bottom
        LEDs 13-24 left side of the ramp, bottom to top
        LEDs 25-27 male dummy (head, torso, lower body)
        LEDs 28-30 female dummy (lower body, torso, head)

Game:
    Three lanes with cars and trucks; every row of traffic leaves a reachable
    free lane. The roadside follows the speed:
        up to 30 km/h   school zone
        up to 50 km/h   city
        up to 100 km/h  Landstrasse (country road)
        over 100 km/h   Autobahn
    Four difficulty levels; the best distance is saved for each level.
    English and German, chosen on the start screen.

Screens (each knob press moves to the next one):
    start screen  -> press: play
    playing       -> crash: GAME OVER
    GAME OVER     -> press: lever screen (pull the lever to the blinking ramp lights)
    lever screen  -> press: countdown 3-2-1-GO, the player lets go of the lever
    after GO      -> crash test replay at the crash speed
    crash replay  -> press: back to the start screen
After IDLE_TIMEOUT seconds without input the game returns to the start screen.

Injury risk is based on US crash data (NASS-CDS); sources are listed at
"Injury risk from real crash data" below.

Controls: turn the encoder = steer / choose, press = next screen.
Keyboard for testing: LEFT / RIGHT, SPACE = button, ESC = quit, F = frames per second.
"""
