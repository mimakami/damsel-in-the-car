def draw_scenery(segs, d):
    decals.clear()
    blend = S(80)
    # 1. ground colour of every visible segment
    visible = []
    for i, (start, key) in enumerate(segs):
        yt = int(clamp(d - seg_end(segs, i), 0, H))
        yb = int(clamp(d - start, 0, H))
        if yb > yt:
            visible.append((i, key, yt, yb))
            gcol = ZONE_GROUND[key]
            fill(gcol, 0, yt, ROAD_L, yb - yt)
            fill(gcol, ROAD_R, yt, W - ROAD_R, yb - yt)
    # 2. colour blend across every boundary (in 2 pixel steps, stays pixelated)
    for i in range(1, len(segs)):
        yb_ = int(d - segs[i][0])
        if -blend < yb_ < H + blend:
            new, old = ZONE_GROUND[segs[i][1]], ZONE_GROUND[segs[i - 1][1]]
            for yy in range(yb_ - blend, yb_ + blend, 2):
                c = lerp_color(new, old, (yy - (yb_ - blend)) / (2.0 * blend))
                fill(c, 0, yy, ROAD_L, 2)
                fill(c, ROAD_R, yy, W - ROAD_R, 2)
    # 3. strips next to the road, per segment
    for i, key, yt, yb in visible:
        screen.set_clip(pygame.Rect(0, yt, W, yb - yt))
        draw_strips(key)
    screen.set_clip(None)
    # 4. areas kept free for the zone entrance signs
    keep = []
    for i in range(1, len(segs)):
        yb_ = int(d - segs[i][0])
        if -BR * 2 < yb_ < H + BR * 2:
            keep += boundary_keepout(segs[i][1], yb_)
    # 5. objects: every object belongs to the zone at its own position
    for i, key, yt, yb in visible:
        fn, mult = ZONE_ITEMS[key]
        P = int(CAR_L * mult)
        for k in range(int((d - H) // P) - 1, int(d // P) + 3):
            if zone_at(segs, k * P - P // 2) != key:
                continue
            y = int(d - k * P)
            for side in (-1, 1):
                avail = ROAD_L if side < 0 else W - ROAD_R
                rng = random.Random((k * 2 + (1 if side > 0 else 0)) * 8 + ZONE_INDEX[key])
                fn(side, k, y, P, rng, avail, Occ(keep))
    # 6. entrance signs where a new zone begins
    for i in range(1, len(segs)):
        yb_ = int(d - segs[i][0])
        if -BR * 2 < yb_ < H + BR * 2:
            boundary_sign(segs[i][1], yb_)


# ---------------------------------------------------------------- scenery cache
# Drawing the roadside every frame is slow on the Pi (the city has many objects).
# The scenery never changes, so it is drawn once into screen-sized "tiles" and then
# only copied. Tile k holds the world positions k*H .. (k+1)*H.
class SceneryCache:
    def __init__(self):
        self.tiles = {}
        self.key = None

    def _render(self, segs, k):
        global screen
        tile = pygame.Surface((W, H)).convert()
        real = screen
        screen = tile
        try:
            draw_scenery(segs, float((k + 1) * H))
        finally:
            screen = real
        return tile, list(decals)

    def draw(self, segs, d):
        key = tuple(segs)
        if key != self.key:                      # a new zone segment: start over
            self.tiles.clear()
            self.key = key
        di = int(d)
        k_lo, k_hi = (di - H) // H, di // H
        zebras = []
        for k in range(k_lo, k_hi + 1):
            if k not in self.tiles:
                self.tiles[k] = self._render(segs, k)
            tile, tile_decals = self.tiles[k]
            y0 = di - (k + 1) * H
            screen.blit(tile, (0, y0))
            zebras += [zy + y0 for zy in tile_decals]
        for k in [k for k in self.tiles if k < k_lo]:
            del self.tiles[k]
        decals[:] = zebras


scenery_cache = SceneryCache()


