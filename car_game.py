def risk(sex, level, kmh):
    """Risk in percent for sex 'M'/'F', level 'mod'/'ser' at a crash speed in km/h."""
    if kmh <= 0:
        return 0.0
    if level == "mod":
        a0, a1 = MOD_LOGIT
        half = 0.5 * math.log(FEMALE_OR_MOD)
        z = a0 + a1 * (kmh / 1.609344) + (half if sex == "F" else -half)
        return 100.0 / (1.0 + math.exp(-z))
    alpha, beta = RISK_WEIBULL[(sex, level)]
    return 100.0 * (1.0 - math.exp(-((kmh / beta) ** alpha)))


def fmt_pct(p):
    if p >= 99.5:
        return ">99%"
    if p < 10:
        return num(p) + "%"
    return f"{p:.0f}%"


RISK_STOPS = [(0, (80, 200, 100)), (15, (240, 210, 60)), (40, (245, 140, 50)),
              (80, (230, 50, 50)), (100, (190, 20, 40))]


def risk_color(p):
    for i in range(1, len(RISK_STOPS)):
        if p <= RISK_STOPS[i][0]:
            p0, c0 = RISK_STOPS[i - 1]
            p1, c1 = RISK_STOPS[i]
            return lerp_color(c0, c1, (p - p0) / (p1 - p0))
    return RISK_STOPS[-1][1]


