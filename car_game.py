# ---------------------------------------------------------------- addressable LEDs
# One WS2812 / NeoPixel chain on one data pin (LED_PIN, default GPIO10 = physical pin 19).
# LED numbers as on the build (1-based):
#    1..12  right side of the ramp, top -> bottom
#   13..24  left side of the ramp, bottom -> top
#   25..27  male dummy:   25 head, 26 torso, 27 lower body
#   28..30  female dummy: 30 head, 29 torso, 28 lower body
DUMMY_LEDS = {
    "M": {"head": 25, "torso": 26, "legs": 27},
    "F": {"head": 30, "torso": 29, "legs": 28},
}
RAMP_STEPS = 12
ZONE_KEYS = ["school", "city", "country", "autobahn"]
ZONE_BANDS = [(0, 30), (30, 50), (50, 100), (100, MAX_KMH)]   # 3 ramp steps per zone


def ramp_pair(h):
    """The two LEDs (right side, left side) at ramp height h = 1 (bottom) .. 12 (top)."""
    return 13 - h, 12 + h


def ramp_height(kmh):
    """Ramp height 1..12 for a crash speed: 3 steps per speed zone, finer inside the zone."""
    z = ZONE_INDEX[zone_for(kmh)[0]]
    lo, hi = ZONE_BANDS[z]
    frac = clamp((kmh - lo) / float(hi - lo), 0.0, 0.999)
    return z * 3 + 1 + int(frac * 3)


# Colours for the real LEDs. WS2812 LEDs need strong, saturated colours: the soft screen
# colours (light green, pale yellow, orange) all look like a similar whitish yellow on them.
LED_ZONE_COLORS = {
    "school": (0, 255, 0), "city": (255, 170, 0),
    "country": (255, 55, 0), "autobahn": (0, 60, 255),
}
LED_RISK_STOPS = [(0, (0, 255, 0)), (15, (130, 255, 0)), (30, (255, 170, 0)),
                  (50, (255, 60, 0)), (70, (255, 0, 0)), (85, (255, 0, 110)), (100, (140, 0, 255))]


def height_color(h):
    return LED_ZONE_COLORS[ZONE_KEYS[(h - 1) // 3]]


def led_risk_color(p):
    """Risk in percent -> LED colour: green, yellow, orange, red, magenta, purple."""
    for i in range(1, len(LED_RISK_STOPS)):
        if p <= LED_RISK_STOPS[i][0]:
            p0, c0 = LED_RISK_STOPS[i - 1]
            p1, c1 = LED_RISK_STOPS[i]
            return lerp_color(c0, c1, (p - p0) / (p1 - p0))
    return LED_RISK_STOPS[-1][1]


def roll_time(kmh):
    """Seconds the real cart rolls from the target step to the end of the ramp."""
    return max(0.25, ROLL_TIME_TOP * math.sqrt(ramp_height(kmh) / float(RAMP_STEPS)))


def scale(c, f):
    f = clamp(f, 0.0, 1.0)
    return (int(c[0] * f), int(c[1] * f), int(c[2] * f))


class LedStrip:
    """Talks to the LED chain. Tries Adafruit's Pi 5 driver (PIO), then Pi5Neo (SPI).
    Without either, the game simply runs without LEDs."""

    def __init__(self, n):
        self.n = n
        self.buf = [(0, 0, 0)] * n
        self.sent = None
        self.dev = None
        self.kind = None
        self.last_err = 0.0
        errors = []
        try:
            import board
            from adafruit_raspberry_pi5_neopixel_write import neopixel_write
            pin = getattr(board, f"D{LED_PIN}")
            self.dev = (neopixel_write, pin)
            self.kind = "pio"
        except Exception as e:
            errors.append(f"Pi5 PIO driver: {e}")
            try:
                from pi5neo import Pi5Neo
                self.dev = Pi5Neo("/dev/spidev0.0", n, 800)
                self.kind = "spi"
            except Exception as e2:
                errors.append(f"Pi5Neo SPI: {e2}")
        if self.kind:
            print(f"LED strip ready ({self.kind}), {n} LEDs.")
        else:
            print("No LED strip:", " | ".join(errors))

    def show(self, buf):
        self.buf = buf
        dummy_idx = {n - 1 for d in DUMMY_LEDS.values() for n in d.values()}
        out = [scale(c, DUMMY_BRIGHTNESS if i in dummy_idx else LED_BRIGHTNESS) for i, c in enumerate(buf)]
        if out == self.sent or not self.dev:
            return
        self.sent = out
        try:
            if self.kind == "pio":
                write, pin = self.dev
                data = bytearray()
                for r, gg, b in out:        # WS2812 expects the bytes in the strip's colour order
                    data += bytes((gg, r, b)) if LED_ORDER == "GRB" else bytes((r, gg, b))
                write(pin, data)
            else:
                for i, (r, gg, b) in enumerate(out):
                    rr, g2, b2 = {"GRB": (r, gg, b), "RGB": (gg, r, b)}.get(LED_ORDER, (r, gg, b))
                    self.dev.set_led_color(i, rr, g2, b2)
                self.dev.update_strip()
        except Exception as e:
            # report the problem (once every 5 s) and keep trying instead of giving up
            if time.time() - self.last_err > 5:
                print("LED error:", repr(e))
                self.last_err = time.time()
            self.sent = None

    def off(self):
        self.show([(0, 0, 0)] * self.n)


leds = LedStrip(LED_COUNT)


def dummy_colors(kmh):
    """Colour per body region = injury severity if you hit a wall at kmh.
    Lower body: moderate+ risk (most moderate injuries and the largest female excess are
    in the legs: Forman et al. 2019, Brumbelow & Jermakian 2022).
    Torso and head: serious+ risk (AIS 3+ or death, Funk et al. 2008), same colour. Green = low risk -> yellow -> orange -> red -> purple = almost certain.
    Returns colour and risk in percent per region."""
    out = {}
    for sex in ("M", "F"):
        out[sex] = {}
        for part, lvl in (("legs", "mod"), ("torso", "ser"), ("head", "ser")):
            p = risk(sex, lvl, kmh)
            out[sex][part] = (led_risk_color(p), p)
    return out


def led_frame(g, now):
    """Work out all 30 LED colours from the game state, once per frame."""
    buf = [(0, 0, 0)] * LED_COUNT
    st = g["state"]
    crash = g["crash_kmh"]

    def put(n, c):
        buf[n - 1] = c

    def ramp(h, c):
        a, b = ramp_pair(h)
        put(a, c)
        put(b, c)

    def dummies(kmh, f=1.0, parts=("legs", "torso", "head")):
        cols = dummy_colors(kmh)
        for sex in ("M", "F"):
            for part in parts:
                c, p = cols[sex][part]
                put(DUMMY_LEDS[sex][part], scale(c, f))

    def rolling(time_to_impact):
        """A light that rolls down the ramp like the cart, reaching the bottom at impact."""
        target = ramp_height(crash)
        R = roll_time(crash)
        r = clamp(1.0 - time_to_impact / R, 0.0, 1.0)
        pos = target - (target - 1) * r * r
        for h in range(1, target + 1):
            d = h - pos
            if 0 <= d < 3:
                ramp(h, scale((255, 255, 255), 1.0 - d / 3.0))

    if st == "title":                        # slow wave climbing up the ramp
        for h in range(1, RAMP_STEPS + 1):
            k = 0.5 + 0.5 * math.sin(now * 2.0 - h * 0.6)
            ramp(h, scale(height_color(h), 0.06 + 0.4 * k * k))
    elif st == "play":                       # live speed bar, dummies show the risk right now
        top = ramp_height(g["kmh"])
        for h in range(1, top + 1):
            f = 1.0 if h < top else 0.55 + 0.45 * math.sin(now * 10)
            ramp(h, scale(height_color(h), f))
        dummies(g["kmh"], 0.45)
    elif st == "over":
        top = ramp_height(crash)
        for h in range(1, top + 1):
            ramp(h, height_color(h))
        dummies(crash)
    elif st == "lever":                      # path to the target, target blinks; dummies dark
        target = ramp_height(crash)
        for h in range(1, target):
            ramp(h, scale(height_color(h), 0.15))
        ramp(target, (255, 255, 255) if int(now * 4) % 2 == 0 else height_color(target))
    elif st == "count":
        target = ramp_height(crash)
        t = g["count_t"]
        if t < 3 * COUNT_STEP:               # 3-2-1: target steady, path pulses with each number
            f = 1.0 - (t % COUNT_STEP) / COUNT_STEP
            for h in range(1, target):
                ramp(h, scale(height_color(h), 0.12 + 0.6 * f ** 3))
            ramp(target, (255, 255, 255))
        else:                                # GO: a light "rolls" down like the cart
            rolling(roll_time(crash) - (t - 3 * COUNT_STEP))   # follows the real cart
    elif st == "replay":
        ti = g["replay_t"] - replay_hit_time(crash)
        if ti < 0:
            rolling(roll_time(crash) - g.get("since_go", 99.0))
        else:
            if ti < 0.15:                    # impact flash
                for sex in ("M", "F"):
                    for n in DUMMY_LEDS[sex].values():
                        put(n, (255, 255, 255))
            else:                            # severity appears: lower body, torso, head
                for part, t0 in (("legs", 0.15), ("torso", 0.45), ("head", 0.75)):
                    if ti >= t0:
                        dummies(crash, (ti - t0) / 0.2, (part,))
            red = 0.9 * math.exp(-ti * 3)
            top = ramp_height(crash)
            for h in range(1, RAMP_STEPS + 1):
                base = scale(height_color(h), 0.25) if h <= top else (0, 0, 0)
                rc = scale((255, 0, 0), red)
                ramp(h, tuple(max(base[i], rc[i]) for i in range(3)))
    leds.show(buf)
    return buf


