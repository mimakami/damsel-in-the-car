class Occ:
    """Remembers which screen rectangles are already used by an object."""

    def __init__(self, keep):
        self.rects = list(keep)

    def free(self, rect, pad=1):
        return rect.inflate(pad * 2, pad * 2).collidelist(self.rects) == -1

    def add(self, rect):
        self.rects.append(rect)

    def take(self, rect, pad=1):
        if self.free(rect, pad):
            self.rects.append(rect)
            return True
        return False


