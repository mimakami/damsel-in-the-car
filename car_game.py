def blit_text(txt, fnt, col, x, y, align="left", shadow=None):
    t = fnt.render(txt, False, col)
    r = t.get_rect()
    if align == "center":
        r.midtop = (int(x), int(y))
    elif align == "right":
        r.topright = (int(x), int(y))
    else:
        r.topleft = (int(x), int(y))
    if shadow:
        screen.blit(fnt.render(txt, False, shadow), r.move(1, 1))
    screen.blit(t, r)
    return r


def wrap_text(txt, fnt, maxw):
    lines, cur = [], ""
    for word in txt.split():
        trial = (cur + " " + word).strip()
        if fnt.size(trial)[0] <= maxw:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


